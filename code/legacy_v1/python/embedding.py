TOP_N = 200                      # 기간별 추출 수
REFERENCE_DATE = datetime(2026, 3, 1)  # 경과연수 계산 기준일
MIN_YEARS = 0.5                  # 최소 경과연수 (6개월) — 극단값 방지

OUTPUT_PER_PERIOD = True         # 기간별 파일도 저장할지
