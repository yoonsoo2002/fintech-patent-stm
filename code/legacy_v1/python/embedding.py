import pandas as pd
import numpy as np
import os
import warnings
warnings.filterwarnings('ignore')

# ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
# 0. 설정
# ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

INPUT_FILE = 'merged_3files.csv'
OUTPUT_FILE = 'fintech_patents_family_cleaned.csv'

# IP5 국가 코드
IP5_CODES = {'US', 'EP', 'CN', 'JP', 'KR'}

# 기간 구분 기준 (우선권 연도 기반으로 자동 부여)
PERIOD_BREAKS = {
    'Phase1_AI_Blockchain_2019_2021': (2019, 2021),
    'Phase2_LLM_Inflection_2022_2023': (2022, 2023),
    'Phase3_GenAI_OpenBanking_2024_2026': (2024, 2026),
}


# ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
# 1. 데이터 로드 (CSV 파싱 오류 방어 포함)
# ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

def load_data(path):
    """
    CSV 로드 시 'EOF inside string' 등 파싱 오류 방어.
    - 1차: 기본 C 엔진으로 시도
    - 2차: Python 엔진 + on_bad_lines='skip'으로 재시도
    - 3차: 추가로 quoting=3(QUOTE_NONE)까지 적용
    """
    print(f"  로딩: {path}")

    # 1차 시도: 기본 C 엔진
    try:
        df = pd.read_csv(path, low_memory=False)
        print(f"  ✅ {len(df):,}건 로드됨 (C 엔진) | 컬럼 {len(df.columns)}개")
        return df
    except Exception as e:
        print(f"  ⚠️  C 엔진 실패: {e}")

    # 2차 시도: Python 엔진 + 불량 행 스킵
    try:
        df = pd.read_csv(path, low_memory=False, engine='python', on_bad_lines='skip')
        print(f"  ✅ {len(df):,}건 로드됨 (Python 엔진, bad lines skip) | 컬럼 {len(df.columns)}개")
        return df
    except Exception as e:
        print(f"  ⚠️  Python 엔진도 실패: {e}")

    # 3차 시도: 따옴표 무시 모드
    import csv
    try:
        df = pd.read_csv(
            path, low_memory=False, engine='python',
            on_bad_lines='skip', quoting=csv.QUOTE_NONE
        )
        print(f"  ✅ {len(df):,}건 로드됨 (QUOTE_NONE 모드) | 컬럼 {len(df.columns)}개")
        return df
    except Exception as e:
        raise RuntimeError(f"  ❌ CSV 로드 완전 실패: {e}")


# ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
# 2. 기초 전처리
# ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

def basic_preprocessing(df):

    # (A) Title [SEP] Abstract 결합
    df['Title'] = df['Title'].fillna('')
    df['Abstract'] = df['Abstract'].fillna('')
    df['_text'] = df['Title'].str.strip() + ' [SEP] ' + df['Abstract'].str.strip()
    df['_text_len'] = df['_text'].str.len()

    # (B) 날짜 변환
    for col in ['Earliest Priority Date', 'Application Date', 'Publication Date']:
        if col in df.columns:
            df[col] = pd.to_datetime(df[col], errors='coerce')

    # (C) 피인용수 정수화
    df['Cited by Patent Count'] = pd.to_numeric(
        df['Cited by Patent Count'], errors='coerce'
    ).fillna(0).astype(int)

    # (D) 빈 텍스트 제거
    before = len(df)
    df = df[df['_text_len'] > 10].copy()
    if before > len(df):
        print(f"  텍스트 부족 행 제거: {before - len(df):,}건")

    # (E) IP5 필터
    if 'Jurisdiction' in df.columns:
        non_ip5 = (~df['Jurisdiction'].isin(IP5_CODES)).sum()
        if non_ip5 > 0:
            print(f"  비-IP5 관할 문헌 {non_ip5:,}건 제거")
            df = df[df['Jurisdiction'].isin(IP5_CODES)].copy()

    # (F) 기간 라벨 (출원일 Application Date 기준)
    df['_app_year'] = df['Application Date'].dt.year

    def assign_period(year):
        if pd.isna(year):
            return 'Unknown'
        y = int(year)
        for label, (s, e) in PERIOD_BREAKS.items():
            if s <= y <= e:
                return label
        return 'Unknown'

    df['Period'] = df['_app_year'].apply(assign_period)

    print(f"  기간별 분포:")
    for p, c in df['Period'].value_counts().sort_index().items():
        print(f"    {p}: {c:,}건")
    print(f"  ✅ 전처리 완료: {len(df):,}건")
    return df


