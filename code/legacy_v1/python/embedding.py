# 3. 패밀리 ID 결정
# ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

def assign_family_id(df):

    if 'Extended Family Members' in df.columns:
        def normalize_family(members_str):
            if pd.isna(members_str) or str(members_str).strip() == '':
                return None
            members = sorted(set(
                m.strip() for m in str(members_str).split(';;') if m.strip()
            ))
            return '||'.join(members) if members else None

        df['_family_key'] = df['Extended Family Members'].apply(normalize_family)
        no_family = df['_family_key'].isna()
        df.loc[no_family, '_family_key'] = df.loc[no_family, 'Lens ID']
        print(f"  Extended Family 기반 패밀리 ID 생성")
        print(f"  고유 패밀리 수: {df['_family_key'].nunique():,}")
    else:
        print("  [경고] Extended Family Members 없음 → Lens ID 사용")
        df['_family_key'] = df['Lens ID']

    return df


# ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
# 4. 최초 우선권 국가 추출
# ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

def extract_priority_country(priority_numbers_str, jurisdiction_fallback):
    """
    Priority Numbers에서 최초 우선권 국가 코드 추출.
    예: 'US 202117546446 A;;KR 20190012345 A' → 'US'
    """
    if pd.isna(priority_numbers_str) or str(priority_numbers_str).strip() == '':
        return jurisdiction_fallback

    for p in str(priority_numbers_str).split(';;'):
        p = p.strip()
        if len(p) >= 2:
            country = p[:2].upper()
            if country in IP5_CODES:
                return country
    return jurisdiction_fallback


# ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
# 5. [핵심] 패밀리별 대표 선정 + 메타데이터 융합
# ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

def process_family_group(group):

    # (1) 텍스트 대표: _text_len 최대
    rep = group.loc[group['_text_len'].idxmax()].copy()

    # (2) 최초 우선권 국가
    earliest_idx = group['Earliest Priority Date'].idxmin()
    earliest_row = group.loc[earliest_idx]
    origin = extract_priority_country(
        earliest_row.get('Priority Numbers', ''),
        earliest_row.get('Jurisdiction', 'UNKNOWN')
    )
    rep['Origin_Country'] = origin

    # (3) 패밀리 규모
    if 'Extended Family Size' in group.columns:
        rep['Final_Family_Size'] = group['Extended Family Size'].max()
    else:
        rep['Final_Family_Size'] = len(group)

    # (4) 진입 시장
    if 'Extended Family Member Jurisdictions' in group.columns:
        markets = set()
        for j in group['Extended Family Member Jurisdictions'].dropna():
            for code in str(j).split(';;'):
                c = code.strip()
                if c:
                    markets.add(c)
        rep['Target_Markets'] = ';;'.join(sorted(markets)) if markets else ''
        rep['Target_Market_Count'] = len(markets)
    else:
        jurs = set(group['Jurisdiction'].dropna().unique())
        rep['Target_Markets'] = ';;'.join(sorted(jurs))
        rep['Target_Market_Count'] = len(jurs)

    # (5) 패밀리 내 최대 피인용수
    rep['Family_Max_Cited'] = group['Cited by Patent Count'].max()

    # (6) 우선권 연도
    if pd.notna(earliest_row['Earliest Priority Date']):
        rep['Priority_Year'] = int(earliest_row['Earliest Priority Date'].year)
    else:
        rep['Priority_Year'] = rep.get('Publication Year', np.nan)

    return rep


def deduplicate_families(df):

    n_families = df['_family_key'].nunique()
    print(f"\n{'='*60}")
    print(f"  패밀리 정제 시작")
    print(f"  입력: {len(df):,}건 | 고유 패밀리: {n_families:,}개")
    print(f"{'='*60}")

    try:
        from tqdm import tqdm
        tqdm.pandas(desc="  패밀리 정제 중")
        result = df.groupby('_family_key').progress_apply(process_family_group)
    except ImportError:
        print("  (진행바 없이 처리 — 잠시 기다려주세요...)")
        result = df.groupby('_family_key').apply(process_family_group)

    result = result.reset_index(drop=True)
    print(f"\n  ✅ 패밀리 정제 완료")
    print(f"  출력: {len(result):,}건 (중복 제거: {len(df) - len(result):,}건)")
    return result


