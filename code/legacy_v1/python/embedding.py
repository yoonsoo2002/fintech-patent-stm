input_file = 'patent_classification_results.tsv'
output_file = 'patent_classification_results_clean.csv'

# 기대하는 컬럼의 개수 (헤더 기준 36개)
EXPECTED_COLS = 36

with open(input_file, 'r', encoding='utf-8') as infile, \
     open(output_file, 'w', encoding='utf-8-sig', newline='') as outfile:

    # quoting=csv.QUOTE_MINIMAL: 쉼표가 들어있는 문장들을 안전하게 큰따옴표로 감쌈
    writer = csv.writer(outfile, quoting=csv.QUOTE_MINIMAL)

    for i, line in enumerate(infile):
        line = line.rstrip('\n')
        # 우선 5칸 공백으로 전부 나눔 (초록/근거 때문에 50~80개로 쪼개짐)
        parts = line.split('     ')

        if len(parts) == EXPECTED_COLS:
            writer.writerow(parts)
            continue

        try:
            # 기준점 찾기: 역순으로 탐색하며 'confidence(high/medium/low)'와 'seed_quality(상/중/하)'를 찾음
            C = -1
            for j in range(len(parts) - 1, 0, -1):
                if parts[j] in ['high', 'medium', 'low', 'none', 'confidence'] and parts[j-1] in ['상', '중', '하', 'seed_quality']:
                    C = j
                    break

            if C != -1:
                # 1. 왼쪽 안전한 열 (Lens ID, _family_key, Title) 복원
                left_cols = parts[:3]
                title = parts[2]

                # 2. 오른쪽 안전한 열 (_text_len 부터 confidence 까지 30개 컬럼) 복원
                right_cols = parts[C-29 : C+1]

                # 3. reason 복원 (confidence 다음 위치부터 끝까지 다시 합침)
                reason = "     ".join(parts[C+1:])

                # 4. 중간에 끼어 쪼개진 Abstract와 _text 복원
                middle_str = "     ".join(parts[3 : C-29])

                # _text는 항상 "Title [SEP] Abstract" 구조이므로 이를 기준으로 앞뒤 분리
                sep_marker = f"{title} [SEP]"
                if sep_marker in middle_str:
                    split_idx = middle_str.find(sep_marker)
                    abstract = middle_str[:split_idx].strip()
                    _text = middle_str[split_idx:].strip()
                else:
                    abstract = middle_str
                    _text = middle_str

                # 36개 컬럼으로 완벽하게 조립 완료!
                final_row = left_cols + [abstract, _text] + right_cols + [reason]
                writer.writerow(final_row)
            else:
                # 패턴을 못 찾는 예외의 경우
                fallback_row = parts[:35] + ["     ".join(parts[35:])]
                writer.writerow(fallback_row)

        except Exception as e:
            print(f"Error on line {i}: {e}")
            writer.writerow(parts[:36])  # 에러 방지용

