full_vecs = np.load('full_patents_vectors.npy')

# 코사인 유사도 행렬 계산 (한 번만 계산해두면 K를 계속 바꿔가며 쓸 수 있습니다)
print("전체 특허와 시드 간의 코사인 유사도를 계산 중입니다...")
sim_matrix_pos = cosine_similarity(full_vecs, pos_vecs)
sim_matrix_neg = cosine_similarity(full_vecs, neg_vecs)

# ==========================================
# 1. K=1, 3, 5, 7, 9 민감도 분석 및 Jaccard 유사도 계산
# ==========================================
k_values = [1, 3, 5, 7, 9]
results_dict = {}

print("\n💡 [K값 변화에 따른 핀테크 판별 결과]")
for k in k_values:
    # 각 K값에 대한 Top-K 평균 계산
    pos_avg = np.sort(sim_matrix_pos, axis=1)[:, -k:].mean(axis=1)
    neg_avg = np.sort(sim_matrix_neg, axis=1)[:, -k:].mean(axis=1)

    # 판별 결과 저장 (True/False)
    is_fintech = pos_avg > neg_avg
    results_dict[k] = is_fintech
    print(f" - K={k} 일 때 핀테크 판별 건수: {is_fintech.sum():,}건")

# Jaccard 유사도 행렬 계산 함수 (교집합 / 합집합)
def jaccard_similarity(list1, list2):
    intersection = np.logical_and(list1, list2).sum()
    union = np.logical_or(list1, list2).sum()
    return intersection / union if union != 0 else 0

jaccard_matrix = np.zeros((len(k_values), len(k_values)))
for i, k1 in enumerate(k_values):
    for j, k2 in enumerate(k_values):
        jaccard_matrix[i, j] = jaccard_similarity(results_dict[k1], results_dict[k2])

# 기준값(K=3)과 다른 K값들의 평균 일치율(Robustness) 확인
k3_comparisons = [jaccard_similarity(results_dict[3], results_dict[k]) for k in k_values if k != 3]
mean_jaccard_k3 = np.mean(k3_comparisons)
print(f"\n🔥 [논문 기재용 핵심 수치] K=3 기준, 타 K값들과의 평균 자카드 유사도: {mean_jaccard_k3*100:.2f}%")

# ==========================================
# 2. 민감도 분석 시각화 (Jaccard Heatmap)
# ==========================================
plt.figure(figsize=(7, 5))
sns.heatmap(jaccard_matrix, annot=True, fmt=".3f", cmap="YlGnBu",
            xticklabels=[f"K={k}" for k in k_values],
            yticklabels=[f"K={k}" for k in k_values], vmin=0.8, vmax=1.0)
plt.title("K값 변화에 따른 판별 결과 자카드 유사도 (Jaccard Similarity)", fontsize=14, pad=15)
