# 6. 최종 정리 및 저장
# ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

def finalize_and_save(df, output_path):

    core_cols = [
        'Lens ID', '_family_key',
        'Title', 'Abstract', '_text', '_text_len',
        'Origin_Country', 'Jurisdiction', 'Priority_Year',
        'Publication Year', 'Period',
        'Cited by Patent Count', 'Family_Max_Cited', 'Cites Patent Count',
        'Final_Family_Size', 'Target_Markets', 'Target_Market_Count',
        'CPC Classifications', 'IPCR Classifications',
        'Applicants', 'Owners', 'Application Date',
        'Earliest Priority Date', 'Priority Numbers',
        'Legal Status', 'Display Key', 'URL',
    ]

    available = [c for c in core_cols if c in df.columns]
    df_final = df[available].copy()

    print(f"\n{'='*60}")
    print(f"  최종 데이터 요약")
    print(f"{'='*60}")
    print(f"  총 문헌 수: {len(df_final):,}")

    print(f"\n  ── 기간별 분포 ──")
    for p, c in df_final['Period'].value_counts().sort_index().items():
        print(f"    {p}: {c:,}건")

    print(f"\n  ── 국가별 분포 (Origin_Country) ──")
    for co, c in df_final['Origin_Country'].value_counts().head(10).items():
        print(f"    {co}: {c:,}건 ({c/len(df_final)*100:.1f}%)")

    tl = df_final['_text_len']
    print(f"\n  ── 텍스트 길이 ──")
    print(f"    평균: {tl.mean():.0f}자 | 중간값: {tl.median():.0f}자 | 최대: {tl.max():.0f}자")

    cited = df_final['Cited by Patent Count']
    print(f"\n  ── 피인용수 ──")
    print(f"    평균: {cited.mean():.1f} | 중간값: {cited.median():.0f} | 상위5%: {cited.quantile(0.95):.0f} | 최대: {cited.max():.0f}")

    df_final.to_csv(output_path, index=False, encoding='utf-8-sig')
    print(f"\n  ✅ 저장 완료: {output_path}")
    print(f"     파일 크기: {os.path.getsize(output_path) / (1024**2):.1f} MiB")
    return df_final


