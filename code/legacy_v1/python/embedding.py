# 2. 기초 전처리
# ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

def basic_preprocessing(df):

    # (A) Title [SEP] Abstract 결합
    df['Title'] = df['Title'].fillna('')
    df['Abstract'] = df['Abstract'].fillna('')
    df['_text'] = df['Title'].str.strip() + ' [SEP] ' + df['Abstract'].str.strip()
    df['_text_len'] = df['_text'].str.len()

    # (B) 날짜 변환
    for col in ['Earliest Priority Date', 'Application Date', 'Publication Date']:
        if col in df.columns:
            df[col] = pd.to_datetime(df[col], errors='coerce')

    # (C) 피인용수 정수화
    df['Cited by Patent Count'] = pd.to_numeric(
        df['Cited by Patent Count'], errors='coerce'
    ).fillna(0).astype(int)

    # (D) 빈 텍스트 제거
    before = len(df)
    df = df[df['_text_len'] > 10].copy()
    if before > len(df):
        print(f"  텍스트 부족 행 제거: {before - len(df):,}건")

    # (E) IP5 필터
    if 'Jurisdiction' in df.columns:
        non_ip5 = (~df['Jurisdiction'].isin(IP5_CODES)).sum()
        if non_ip5 > 0:
            print(f"  비-IP5 관할 문헌 {non_ip5:,}건 제거")
            df = df[df['Jurisdiction'].isin(IP5_CODES)].copy()

    # (F) 기간 라벨 (출원일 Application Date 기준)
    df['_app_year'] = df['Application Date'].dt.year

    def assign_period(year):
        if pd.isna(year):
            return 'Unknown'
        y = int(year)
        for label, (s, e) in PERIOD_BREAKS.items():
            if s <= y <= e:
                return label
        return 'Unknown'

    df['Period'] = df['_app_year'].apply(assign_period)

    print(f"  기간별 분포:")
    for p, c in df['Period'].value_counts().sort_index().items():
        print(f"    {p}: {c:,}건")
    print(f"  ✅ 전처리 완료: {len(df):,}건")
    return df


